/**
 * Where the shared dictionary is copied to before being packaged.
 *
 * Resolved to a plain [File] rather than a `Provider`: AGP 9 refuses `Provider` instances
 * in the SourceSet API, because it cannot tell whether the directory holds generated
 * read-only files or static read-write ones. The path is resolved now; the directory itself
 * is created by [syncDictionaryAsset], which `preBuild` depends on.
 */
val dictionaryAssetsDir = layout.buildDirectory.dir("generated/dictionaryAssets")

/**
 * The dictionary is generated by `packages/core` (`npm run build:dict`) into
 * `packages/web/public/dictionary.btree`, which is gitignored. The web app and this keyboard
 * read that same file, so it is copied into the APK instead of being generated twice.
 *
 * The Candidate detail file, `detail.bin`, is built alongside it by the same command and
 * carries the same build id (ADR 0002), so the two are always copied together: shipping
 * one without the other, or from another build, is a failed load at runtime.
 *
 * The bigram table, `bigrams.bin`, is built by `npm run build:bigrams` into the same folder and
 * copied with them when it is there. It is optional: without it the keyboard ranks Sentence
 * candidates on unigram frequencies alone, so a missing table is not an error. It is keyed by
 * simplified form rather than entry id, so it does not need the dictionary's build id.
 */
val syncDictionaryAsset by tasks.registering(Copy::class) {
    description = "Copies the shared generated dictionary.btree, detail.bin and bigrams.bin into the app assets."
    val sources = listOf("dictionary.btree", "detail.bin").map { rootProject.file("../web/public/$it") }
    val optional = rootProject.file("../web/public/bigrams.bin")
    onlyIf {
        sources.firstOrNull { !it.isFile }?.let { missing ->
            throw GradleException(
                "Missing ${missing.absolutePath}. Run \"npm run build:dict\" at the repository " +
                    "root to generate it before building the Android app.",
            )
        }
        true
    }
    from(sources)
    from(optional)
    into(dictionaryAssetsDir)
}

/**
 * Where the release signing credentials come from, when they are available at all.
 *
 * `key.properties` is gitignored, because it holds passwords and a keystore path. A fresh
 * clone, CI, and anyone who is only sideloading therefore do not have one, so the release
 * build has to degrade to an unsigned APK rather than fail — which is what Android produces
 * by default and is installable for local testing.
 *
 * Resolved against [rootProject] deliberately. Inside a module, `file()` resolves against the
 * module directory, so a relative `storeFile` would quietly mean `app/<path>` rather than the
 * project root a reader would assume.
 */
val keystoreProperties =
    Properties().apply {
        val file = rootProject.file("key.properties")
        if (file.isFile) {
            file.inputStream().use { load(it) }
        }
    }

/** True when [keystoreProperties] names a keystore that is actually on disk. */
val hasReleaseKeystore =
    keystoreProperties
        .getProperty("storeFile")
        ?.let { rootProject.file(it) }
        ?.isFile == true

android {
    namespace = "dev.pinyinduck.android"
    compileSdk = 37

    defaultConfig {
        applicationId = "dev.pinyinduck.android"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
    }

    sourceSets {
        getByName("main") {
            assets.srcDir(dictionaryAssetsDir.get().asFile)
        }
    }

    androidResources {
        // The keyboard mmaps `dictionary.btree` straight out of the APK, which is only
        // possible when the asset is stored uncompressed. Compressing it would also
        // shrink the APK by ~5MB, but `AssetFileDescriptor.openFd` throws on a
        // compressed entry and the dictionary would have to be read into the heap,
        // which is exactly what the paged format exists to avoid. The Candidate detail file
        // (`detail.bin`, ~7MB) is mmapped for the same reason, so a record is read on demand.
        noCompress += listOf("btree", "bin")
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Applied only when a keystore is actually present. Leaving it unset otherwise is
            // what makes AGP emit `app-release-unsigned.apk`, which is the correct outcome for
            // a build with no credentials rather than a configuration error.
            if (hasReleaseKeystore) {
                signingConfig =
                    signingConfigs.create("release") {
                        storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                        storePassword = keystoreProperties.getProperty("storePassword")
                        keyAlias = keystoreProperties.getProperty("keyAlias")
                        keyPassword = keystoreProperties.getProperty("keyPassword")
                    }
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "META-INF/*.version")
    }

    testOptions {
        unitTests {
            // Robolectric needs the merged resources and manifest to build a context.
            isIncludeAndroidResources = true

            all {
                it.useJUnit()

                // Unit tests read the real 9.1MB asset (and the detail.bin beside it) so ranking is verified against the
                // same corpus the web app serves, rather than a hand-written fixture.
                it.systemProperty(
                    "pinyinduck.dictionary",
                    rootProject.file("../web/public/dictionary.btree").absolutePath,
                )
                it.systemProperty("robolectric.logging.enabled", "false")

                it.extensions.configure<JacocoTaskExtension> {
                    isIncludeNoLocationClasses = true
                    // Never instrument the JDK itself; Jacoco otherwise trips over the
                    // reflection accessors it generates for Serializable lambdas.
                    excludes = listOf("jdk.internal.*") + coverageExcludedClasses
                }
            }
        }
    }
}

