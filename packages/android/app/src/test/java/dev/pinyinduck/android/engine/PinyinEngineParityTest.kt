package dev.pinyinduck.android.engine

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Ignore
import org.junit.Test

/**
 * Asserts the Kotlin engine reproduces the TypeScript engine's output exactly.
 *
 * `packages/android` ports the engine rather than sharing a bundle with the web app. That
 * is what allows a synchronous lookup inside `onKeyDown`, but it means a change to
 * `scoreEntry`, to the tie-break order or to the B-tree descent would reorder candidates on
 * one platform only, and nothing in either test suite would notice.
 *
 * The golden file is generated by `packages/core/scripts/generate-android-parity.ts`, which
 * runs the real engine over the real dictionary. This test is the guard on that seam.
 */
class PinyinEngineParityTest {
    private data class GoldenCase(
        val query: String,
        val script: ScriptType,
        val total: Int,
        val segments: List<String>,
        val hanzi: List<String>,
        val pinyinMarks: List<String>,
        val glosses: List<String>,
    )

    @Ignore(
        "The golden now pins Sentence candidates, which the Kotlin engine does not build yet: " +
            "https://git.tail68c66a.ts.net/raytray25/pinyin-duck/issues/41",
    )
    @Test
    fun matchesTheTypeScriptEngineExactly() {
        val cases = parseGolden()

        assertTrue("The golden file pinned no queries", cases.isNotEmpty())
        for (case in cases) {
            val label = "${case.query} (${case.script})"
            val actual =
                TestDictionary.engine.search(
                    case.query,
                    SearchOptions(script = case.script, limit = case.hanzi.size),
                )

            // `total` is deliberately not compared for equality. The sources are pinned, but
            // bumping CC-CEDICT to a new edition (packages/core/scripts/sources.ts) can add a
            // word matching one of these queries, which changes the count while leaving the
            // ranking rules — the thing this test exists to protect — untouched. What must hold is
            // that the engine found at least the candidates the golden pins, and that the
            // ranked order, tone marks and glosses are byte-identical.
            assertTrue(
                "candidate total for $label: the golden pins ${case.hanzi.size} but the engine " +
                    "ranked only ${actual.candidates.size} of ${actual.total} matches",
                actual.candidates.size >= case.hanzi.size,
            )
            assertEquals("segments for $label", case.segments, actual.segments)
            assertEquals("ranked characters for $label", case.hanzi, actual.candidates.map { it.hanzi })
            assertEquals("tone marks for $label", case.pinyinMarks, actual.candidates.map { it.pinyinMarks })
            assertEquals("glosses for $label", case.glosses, actual.candidates.map { it.shortGloss })
        }
    }

    @Test
    fun theCorpusIsTheOneTheWebAppServes() {
        // A parity run against an empty or stubbed dictionary would pass every assertion
        // above while proving nothing, so pin that the real asset was actually opened.
        assertTrue("expected the full CC-CEDICT corpus, found ${TestDictionary.entryCount}", TestDictionary.entryCount > 100_000)
        assertTrue("expected a paged asset, found ${TestDictionary.pageCount} pages", TestDictionary.pageCount > 100)
    }

    private fun parseGolden(): List<GoldenCase> {
        val loader = checkNotNull(javaClass.classLoader) { "The test class loader is unavailable" }
        val stream =
            checkNotNull(
                loader.getResourceAsStream(GOLDEN_RESOURCE),
            ) { "$GOLDEN_RESOURCE is missing. Run packages/core/scripts/generate-android-parity.ts." }

        val cases = mutableListOf<GoldenCase>()
        var query: String? = null
        var script = ScriptType.SIMPLIFIED
        var total = 0
        var segments = emptyList<String>()
        val hanzi = mutableListOf<String>()
        val marks = mutableListOf<String>()
        val glosses = mutableListOf<String>()

        fun flush() {
            val started = query ?: return
            cases.add(GoldenCase(started, script, total, segments, hanzi.toList(), marks.toList(), glosses.toList()))
            hanzi.clear()
            marks.clear()
            glosses.clear()
        }

        stream.bufferedReader().forEachLine { line ->
            when {
                line.isBlank() -> flush().also { query = null }
                line.startsWith("#") -> Unit
                line.startsWith(">") -> {
                    flush()
                    // Tab-separated, so a query such as `ni3 hao3` keeps its space.
                    val parts = line.removePrefix(">").split("\t")
                    query = parts[0]
                    script = ScriptType.valueOf(parts[1].uppercase())
                    total = parts[2].toInt()
                }
                line.startsWith("segments ") -> segments = line.removePrefix("segments ").split(" ").filter { it.isNotEmpty() }
                else -> {
                    val fields = line.split("\t")
                    hanzi.add(fields[0])
                    marks.add(fields[1])
                    glosses.add(fields.getOrElse(2) { "" })
                }
            }
        }
        flush()
        stream.close()

        return cases
    }

    private companion object {
        const val GOLDEN_RESOURCE = "engine-parity.tsv"
    }
}
