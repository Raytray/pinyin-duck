/**
 * Generates the golden candidate output that pins the Kotlin engine to the TypeScript one.
 *
 * `packages/android` is a port of this package's engine rather than a shared bundle, which
 * is what keeps lookups synchronous inside `onKeyDown` with no JS bridge. The cost of that
 * choice is that the two implementations can drift: a change to `scoreEntry` or to the
 * B-tree descent would silently reorder candidates on one platform only.
 *
 * This script closes that gap. It runs the real engine over the real `dictionary.btree` for
 * a generated query set (see `parity-cases.ts`) and writes what it found to a line-oriented
 * golden file that `PinyinEngineParityTest` asserts the Kotlin engine reproduces exactly.
 *
 * Usage (from `packages/core`):
 *
 *   npx tsx scripts/generate-android-parity.ts
 *
 * It also writes `fixed-word-parity.tsv`, the Fixed word and span alternatives cases (a
 * separate file so the `engine-parity.tsv` format stays as the Kotlin parser reads it), and
 * `detail-parity.tsv`, the Candidate detail view for every entry those queries
 * reach (see `detail-parity.ts`), which pins the Kotlin detail view the same way.
 *
 * Re-run it whenever the ranking rules, the dictionary or the detail view change, and commit
 * the result alongside those changes.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

import { LazyPinyinSearchEngine } from '../src/index/lazy-search.js';
import { BTreeDictionary } from '../src/data/btree-dictionary.js';
import { BigramTable } from '../src/bigram/bigram-codec.js';
import { DetailFile } from '../src/detail/detail-codec.js';
import { ALTERNATIVES_CASES, buildParityCases, FIXED_WORD_CASES } from './parity-cases.js';
import type { Candidate } from '../src/types.js';
import { detailParityLines } from './detail-parity.js';

const here = path.dirname(fileURLToPath(import.meta.url));

/** The committed asset both clients read. */
const DICTIONARY_PATH = path.resolve(here, '../../web/public/dictionary.btree');

/** The bigram table Sentence candidates score with; the golden is pinned with it loaded. */
const BIGRAMS_PATH = path.resolve(here, '../../web/public/bigrams.bin');

/** The Candidate detail file built alongside it. */
const DETAIL_PATH = path.resolve(here, '../../web/public/detail.bin');

/** Where the Kotlin tests look for the golden files. */
const RESOURCES = path.resolve(here, '../../android/app/src/test/resources');
const OUTPUT_PATH = path.join(RESOURCES, 'engine-parity.tsv');
const DETAIL_OUTPUT_PATH = path.join(RESOURCES, 'detail-parity.tsv');
const FIXED_OUTPUT_PATH = path.join(RESOURCES, 'fixed-word-parity.tsv');

/**
 * How many candidates each query pins. Deep enough that a ranking change anywhere in the
 * list is caught, shallow enough to keep the golden reviewable.
 */
const CANDIDATE_DEPTH = 12;

/** The queries to pin, generated in `parity-cases.ts`. */
const CASES = buildParityCases();

function main(): void {
  for (const [required, command] of [
    [DICTIONARY_PATH, 'build:dict'],
    [DETAIL_PATH, 'build:dict'],
    [BIGRAMS_PATH, 'build:bigrams'],
  ]) {
    if (!fs.existsSync(required)) {
      throw new Error(`Missing ${required}. Run "npm run ${command}" at the repository root first.`);
    }
  }

  const bytes = fs.readFileSync(DICTIONARY_PATH);
  const dictionary = BTreeDictionary.open(bytes);
  const bigrams = BigramTable.open(new Uint8Array(fs.readFileSync(BIGRAMS_PATH)));
  const engine = new LazyPinyinSearchEngine(dictionary, { bigrams });

  const lines: string[] = [
    '# Generated by packages/core/scripts/generate-android-parity.ts. Do not edit by hand.',
    '#',
    '# A record starts with a ">" line holding the query, the script and the total number',
    '# of candidates the engine ranked, tab-separated so a query may contain a space.',
    '# The lines that follow are the top candidates in order, each',
    '# "<hanzi>\\t<pinyin with tone marks>\\t<short gloss>". A Sentence candidate adds a',
    '# words column: three more tab-separated fields per word, "<hanzi>\\t<tone marks>\\t<gloss>",',
    '# in order, so its line has 3 + 3 * words fields. Word candidates have none.',
    '#',
    '# Pinned because packages/android is a port of this engine, with the bigram table loaded.',
    '# Re-run the generator and commit the result whenever the ranking rules, the dictionary',
    '# or the bigram table change.',
    `# entries ${dictionary.entryCount}`,
    `# depth ${CANDIDATE_DEPTH}`,
    '',
  ];

  for (const testCase of CASES) {
    const result = engine.search(testCase.query, {
      script: testCase.script,
      limit: CANDIDATE_DEPTH,
    });

    lines.push(`>${testCase.query}\t${testCase.script}\t${result.total}`);
    lines.push(`segments ${result.segments.join(' ')}`);
    for (const candidate of result.candidates) lines.push(candidateLine(candidate));
    lines.push('');
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');

  console.log(`Wrote ${OUTPUT_PATH}`);
  console.log(`Pinned ${CASES.length} queries over ${dictionary.entryCount} entries.`);

  const fixedLines: string[] = [
    '# Generated by packages/core/scripts/generate-android-parity.ts. Do not edit by hand.',
    '#',
    '# Fixed words and span alternatives (issues #37 and #42), pinned with the bigram table',
    '# loaded. Kept apart from engine-parity.tsv so that file reads as before. Records are',
    '# separated by a blank line, and every field is tab-separated. Two kinds:',
    '#',
    '# >search <query> <script> <total>',
    '#   search(query, { script, fixedWords }) with these fixed words, in list order:',
    '#   fixed <start> <end> <simplified> <traditional> <tone-numbered reading>',
    '#   (start and end are offsets in the toneless query). Then "segments ...", then',
    '#   "spans <start>-<end> ..." for each word of the first candidate when it is a Sentence',
    '#   candidate, then the top candidates in the engine-parity.tsv line format (a Sentence',
    '#   candidate adds "<hanzi> <tone marks> <gloss>" per word).',
    '#',
    '# >alternatives <query> <script> <start> <end> <count>',
    '#   alternativesForSpan(query, { start, end }, { script }): every alternative, in order,',
    '#   as "<hanzi> <tone marks> <gloss>".',
    '#',
    '# The Kotlin engine does not read this yet: https://git.tail68c66a.ts.net/raytray25/pinyin-duck/issues/43',
    '',
  ];
  for (const testCase of FIXED_WORD_CASES) {
    const script = 'simplified';
    const result = engine.search(testCase.query, { script, limit: CANDIDATE_DEPTH, fixedWords: testCase.fixedWords });
    fixedLines.push(`>search\t${testCase.query}\t${script}\t${result.total}`);
    for (const { start, end, word } of testCase.fixedWords) {
      fixedLines.push(['fixed', start, end, word.simplified, word.traditional, word.pinyinNumbers].join('\t'));
    }
    fixedLines.push(`segments ${result.segments.join(' ')}`);
    const words = result.candidates[0]?.words;
    if (words) fixedLines.push(`spans ${words.map(({ span }) => `${span!.start}-${span!.end}`).join(' ')}`);
    for (const candidate of result.candidates) fixedLines.push(candidateLine(candidate));
    fixedLines.push('');
  }
  for (const testCase of ALTERNATIVES_CASES) {
    const script = 'simplified';
    const alternatives = engine.alternativesForSpan(testCase.query, testCase.span, { script });
    fixedLines.push(
      `>alternatives\t${testCase.query}\t${script}\t${testCase.span.start}\t${testCase.span.end}\t${alternatives.length}`
    );
    for (const candidate of alternatives) fixedLines.push(candidateLine(candidate));
    fixedLines.push('');
  }
  fs.writeFileSync(FIXED_OUTPUT_PATH, fixedLines.join('\n'), 'utf8');
  console.log(`Wrote ${FIXED_OUTPUT_PATH}`);
  console.log(`Pinned ${FIXED_WORD_CASES.length} fixed word and ${ALTERNATIVES_CASES.length} alternatives cases.`);

  const detail = DetailFile.open(fs.readFileSync(DETAIL_PATH), dictionary.buildId);
  const detailLines = [
    '# Generated by packages/core/scripts/generate-android-parity.ts. Do not edit by hand.',
    '#',
    '# The Candidate detail view for every entry the engine-parity.tsv queries reach, in both',
    '# scripts, and for every grouped candidate they reach, in simplified script. A record',
    '# starts with a ">" line: simplified, traditional, tone-numbered reading, script and',
    '# number of entries, tab-separated, naming the B+ tree row with those forms, reading and',
    '# entry count. Then, tab-separated:',
    '#   counterpart <hanzi>        when the view shows one',
    '#   group [<heading>]          one per group, with its heading when grouped',
    '#   pos <labels>               the part-of-speech line, when the group has one',
    '#   tag <text>                 each tag',
    '#   sense|proper <n> <text>    each sense; "proper" marks a proper noun sense',
    '#   mw <text>                  each measure word',
    '# and a blank line. See packages/core/scripts/detail-parity.ts.',
    '',
    ...detailParityLines(engine, detail, CASES, CANDIDATE_DEPTH),
  ];
  fs.writeFileSync(DETAIL_OUTPUT_PATH, detailLines.join('\n'), 'utf8');
  const records = detailLines.filter((line) => line.startsWith('>')).length;
  console.log(`Wrote ${DETAIL_OUTPUT_PATH}`);
  console.log(`Pinned ${records} Candidate detail views.`);
}

/** One candidate line: Hanzi, tone marks and gloss, then the same three per word of a sentence. */
function candidateLine(candidate: Candidate): string {
  const fields = [candidate.hanzi, candidate.pinyinMarks, candidate.shortGloss];
  for (const word of candidate.words ?? []) fields.push(word.hanzi, word.pinyinMarks, word.shortGloss);
  return fields.join('\t');
}

try {
  main();
} catch (error: unknown) {
  console.error(error);
  process.exitCode = 1;
}
