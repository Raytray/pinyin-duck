/**
 * Generates the golden candidate output that pins the Kotlin engine to the TypeScript one.
 *
 * `packages/android` is a port of this package's engine rather than a shared bundle, which
 * is what keeps lookups synchronous inside `onKeyDown` with no JS bridge. The cost of that
 * choice is that the two implementations can drift: a change to `scoreEntry` or to the
 * B-tree descent would silently reorder candidates on one platform only.
 *
 * This script closes that gap. It runs the real engine over the real `dictionary.btree` for
 * a generated query set (see `parity-cases.ts`) and writes what it found to a line-oriented
 * golden file that `PinyinEngineParityTest` asserts the Kotlin engine reproduces exactly.
 *
 * Usage (from `packages/core`):
 *
 *   npx tsx scripts/generate-android-parity.ts
 *
 * Re-run it whenever the ranking rules or the dictionary change, and commit the result
 * alongside those changes.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

import { LazyPinyinSearchEngine } from '../src/index/lazy-search.js';
import { BTreeDictionary } from '../src/data/btree-dictionary.js';
import { MemoryPageSource } from '../src/data/page-source.js';
import { buildParityCases } from './parity-cases.js';

const here = path.dirname(fileURLToPath(import.meta.url));

/** The committed asset both clients read. */
const DICTIONARY_PATH = path.resolve(here, '../../web/public/dictionary.btree');

/** Where the Kotlin test looks for the golden file. */
const OUTPUT_PATH = path.resolve(here, '../../android/app/src/test/resources/engine-parity.tsv');

/**
 * How many candidates each query pins. Deep enough that a ranking change anywhere in the
 * list is caught, shallow enough to keep the golden reviewable.
 */
const CANDIDATE_DEPTH = 12;

/** The queries to pin, generated in `parity-cases.ts`. */
const CASES = buildParityCases();

async function main(): Promise<void> {
  if (!fs.existsSync(DICTIONARY_PATH)) {
    throw new Error(
      `Missing ${DICTIONARY_PATH}. Run "npm run build:dict" at the repository root first.`
    );
  }

  const bytes = fs.readFileSync(DICTIONARY_PATH);
  const dictionary = await BTreeDictionary.open(new MemoryPageSource(bytes));
  const engine = new LazyPinyinSearchEngine(dictionary);

  const lines: string[] = [
    '# Generated by packages/core/scripts/generate-android-parity.ts. Do not edit by hand.',
    '#',
    '# A record starts with a ">" line holding the query, the script and the total number',
    '# of candidates the engine ranked, tab-separated so a query may contain a space.',
    '# The lines that follow are the top candidates in order, each',
    '# "<hanzi>\\t<pinyin with tone marks>\\t<short gloss>".',
    '#',
    '# Pinned because packages/android is a port of this engine. Re-run the generator and',
    '# commit the result whenever the ranking rules or the dictionary change.',
    `# entries ${dictionary.entryCount}`,
    `# depth ${CANDIDATE_DEPTH}`,
    '',
  ];

  for (const testCase of CASES) {
    const result = await engine.search(testCase.query, {
      script: testCase.script,
      limit: CANDIDATE_DEPTH,
    });

    lines.push(`>${testCase.query}\t${testCase.script}\t${result.total}`);
    lines.push(`segments ${result.segments.join(' ')}`);
    for (const candidate of result.candidates) {
      lines.push(`${candidate.hanzi}\t${candidate.pinyinMarks}\t${candidate.shortGloss}`);
    }
    lines.push('');
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');

  console.log(`Wrote ${OUTPUT_PATH}`);
  console.log(`Pinned ${CASES.length} queries over ${dictionary.entryCount} entries.`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
