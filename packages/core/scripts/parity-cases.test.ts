import { describe, it, expect } from 'vitest';
import * as fs from 'fs';
import * as path from 'path';
import { ALTERNATIVES_CASES, buildParityCases, FIXED_WORD_CASES, queriesForWord, SEED_WORDS } from './parity-cases';

const RESOURCES = path.resolve(__dirname, '../../android/app/src/test/resources');
const GOLDEN_PATH = path.join(RESOURCES, 'engine-parity.tsv');
const FIXED_GOLDEN_PATH = path.join(RESOURCES, 'fixed-word-parity.tsv');

describe('queriesForWord', () => {
  it('puts a tone, and a wrong tone, in each position', () => {
    expect(queriesForWord({ syllables: ['ni3', 'hao3'], covers: '' })).toEqual([
      'nihao',
      'ni3hao3',
      "ni'hao",
      "ni3'hao3",
      'ni3 hao3',
      'Nihao',
      'ni3hao',
      'ni4hao',
      'nihao3',
      'ni4hao3',
      'nihao4',
      'ni3hao4',
    ]);
  });

  it('mixes toned and toneless syllables in a longer word', () => {
    const queries = queriesForWord({ syllables: ['tu3', 'tuo1', 'yu2'], covers: '' });
    expect(queries).toContain('tutuo1yu');
    expect(queries).toContain('tutuo1yu2');
    expect(queries).toContain('tu3tuo1yu');
  });

  it('rejects a seed syllable without a tone digit', () => {
    expect(() => queriesForWord({ syllables: ['ni', 'hao3'], covers: '' })).toThrow(/tone digit/);
  });
});

describe('buildParityCases', () => {
  const cases = buildParityCases();
  const keys = cases.map((c) => `${c.query}\t${c.script}`);

  it('pins 后 hòu in both scripts, where it is one candidate in one and two in the other', () => {
    expect(keys).toContain('hou4\tsimplified');
    expect(keys).toContain('hou4\ttraditional');
  });

  it('pins no query twice', () => {
    expect(new Set(keys).size).toBe(keys.length);
  });

  it('pins every seed query in both scripts', () => {
    for (const seed of SEED_WORDS) {
      for (const query of queriesForWord(seed)) {
        expect(keys).toContain(`${query}\tsimplified`);
        expect(keys).toContain(`${query}\ttraditional`);
      }
    }
  });

  it('keeps the queries that caught earlier drift', () => {
    for (const query of ['shi4', 'ta4', 'lv4', 'ni3hao3', 'nihao3', 'ni3hao', 'bian3', 'hang', "xi'an"]) {
      expect(keys).toContain(`${query}\tsimplified`);
    }
  });
});

/**
 * The golden is regenerated by hand, so these catch a case list edited without re-running
 * `npm run build:parity`: the Kotlin test would otherwise keep passing on the old queries.
 */
describe('engine-parity.tsv', () => {
  const lines = fs.readFileSync(GOLDEN_PATH, 'utf8').split('\n');
  const headers = lines.filter((line) => line.startsWith('>')).map((line) => line.slice(1).split('\t'));
  const candidates = lines.filter((line) => line !== '' && !/^[>#]|^segments /.test(line));

  it('pins exactly the generated cases, in order', () => {
    expect(headers.map(([query, script]) => `${query}\t${script}`)).toEqual(
      buildParityCases().map((c) => `${c.query}\t${c.script}`)
    );
  });

  it('pins candidates outside the BMP', () => {
    expect(candidates.some((line) => [...line.split('\t')[0]].some((ch) => ch.codePointAt(0)! > 0xffff))).toBe(true);
  });
});

describe('fixed-word-parity.tsv', () => {
  const lines = fs.readFileSync(FIXED_GOLDEN_PATH, 'utf8').split('\n');
  const records: string[][] = [];
  for (const line of lines) {
    if (line.startsWith('>')) records.push([line]);
    else if (line !== '' && !line.startsWith('#')) records[records.length - 1]?.push(line);
  }

  it('pins exactly the fixed word cases, then the alternatives cases, in order', () => {
    const fixedLines = (fixedWords: (typeof FIXED_WORD_CASES)[number]['fixedWords']) =>
      fixedWords.map(({ start, end, word }) => `fixed\t${start}\t${end}\t${word.simplified}\t${word.traditional}\t${word.pinyinNumbers}`);
    const expected = [
      ...FIXED_WORD_CASES.map((c) => [`search\t${c.query}\tsimplified`, ...fixedLines(c.fixedWords)]),
      ...ALTERNATIVES_CASES.map((c) => [`alternatives\t${c.query}\tsimplified\t${c.span.start}\t${c.span.end}`]),
    ];
    const pinned = records.map(([header, ...rest]) => {
      const fields = header.slice(1).split('\t');
      // Drop the count the generator appends to each header.
      return [fields.slice(0, -1).join('\t'), ...rest.filter((line) => line.startsWith('fixed\t'))];
    });
    expect(pinned).toEqual(expected);
  });

  it('pins the edited sentence first, with its word spans', () => {
    const [search] = records;
    expect(search.find((line) => line.startsWith('spans '))).toBe('spans 0-2 2-7 7-9 9-14');
    const firstCandidate = search.find((line) => !/^(>|fixed\t|segments |spans )/.test(line))!;
    expect(firstCandidate.split('\t')[0]).toBe('我想喝咖啡');
  });
});
