/**
 * Generates everything the Windows and macOS input methods load.
 *
 * For each platform, writes into `packages/<platform>/rime`:
 *
 * - the schemas, `default.custom.yaml` and the Lua filter, rendered from `templates/`, so
 *   the two platforms differ only where `src/rime-platform.ts` says they do;
 * - one `<name>.dict.yaml` per script and the Lua gloss sidecar, read from the paged B+
 *   tree the rest of the project shares. Nothing is materialized: the tree is walked in key
 *   order and each code is emitted as soon as the walk leaves it, so peak memory is the
 *   largest group of same-reading entries rather than the corpus.
 *
 * Usage:
 *   npm run build:rime                                  # every platform
 *   npm run build:rime -- --platform macos              # one platform
 *   npm run build:rime -- --platform macos --out <dir>  # write one platform somewhere else
 *   npm run build:rime -- --btree <path>                # read a different asset
 */

import * as fs from 'fs';
import * as path from 'path';
import { pathToFileURL } from 'url';
import { BTreeDictionary, MemoryPageSource } from '@pinyinduck/core';
import {
  RIME_SCRIPTS,
  RimeDictWriter,
  formatRow,
  renderDataCredit,
  renderDictHeader,
  type RimeScript,
} from '../src/rime-dict.js';
import {
  PLATFORM_INFO,
  TEMPLATE_FILES,
  flagValue,
  parsePlatformFlag,
  renderTemplate,
  type RimePlatform,
} from '../src/rime-platform.js';

const DEFAULT_BTREE = path.resolve(__dirname, '../../web/public/dictionary.btree');
const TEMPLATES_DIR = path.resolve(__dirname, '../templates');

/** Where a platform's installer reads its files from. */
export function platformRimeDir(platform: RimePlatform): string {
  return path.resolve(__dirname, '../..', platform, 'rime');
}

/**
 * Dictionary names.
 *
 * A dictionary file is only compiled for the schema that names it in
 * `translator/dictionary`, so these have to stay in step with `rime/*.schema.yaml`.
 */
export const DICT_NAMES: Record<RimeScript, string> = {
  simplified: 'pinyinduck',
  traditional: 'pinyinduck_trad',
};

/** Bumped when the emitted layout changes, so Weasel and Squirrel recompile on update. */
export const DICT_VERSION = '0.2.0';

/** Rows buffered before a write, to keep 122k rows from becoming 122k syscalls. */
export const FLUSH_INTERVAL = 4096;

/** Escapes a string for a Lua string literal, keeping it on one line. */
function luaString(value: string): string {
  return (
    '"' +
    value
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t') +
    '"'
  );
}

/** Orders two strings deterministically, so the emitted file is reproducible. */
function compareStrings(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * Renders the Lua gloss sidecar the schema's `lua_filter` reads.
 *
 * The dictionary's comment column holds the definition, but librime discards it at compile
 * time. This module is the same data in a form a Lua filter can look up: candidate text to
 * toneless code to definition. Keyed by code because one text can carry several readings
 * (`绿` is both `lü` and `lu`), and each reading has its own definition.
 *
 * The data is emitted as one delimited string rather than a table literal because a Lua
 * function can hold at most 65536 constants and the corpus has far more definitions than
 * that. The string is a single constant; the table is built from it at load time. Fields are
 * tab-separated and rows newline-separated, which is safe because the emitter sanitizes
 * every field to be free of both.
 */
export function renderGlossSidecar(gloss: Map<string, Map<string, string>>): string {
  const rows: string[] = [];
  for (const text of [...gloss.keys()].sort(compareStrings)) {
    const byCode = gloss.get(text)!;
    for (const [code, comment] of [...byCode.entries()].sort((a, b) => compareStrings(a[0], b[0]))) {
      rows.push(`${text}\t${code}\t${comment}\n`);
    }
  }
  const data = rows.join('');
  return [
    '-- Generated by `npm run build:rime`. Do not edit.',
    '--',
    '-- Maps candidate text to its English definition, keyed by the toneless code the',
    '-- schema matches on. The schema\'s `lua_filter@*pinyinduck_gloss_filter` reads this',
    '-- to put the definition on each candidate. Without it the filter degrades to a',
    '-- pass-through and candidates show their spelling instead of a definition.',
    '--',
    '-- The data is one tab-and-newline delimited string rather than a table literal: a Lua',
    '-- function can hold at most 65536 constants, and the corpus has far more definitions',
    '-- than that. The string is a single constant; the table is built from it at load.',
    '--',
    ...renderDataCredit('--'),
    'local data = ' + luaString(data),
    'local gloss = {}',
    'for text, code, def in data:gmatch("([^\\t]+)\\t([^\\t]+)\\t([^\\n]+)\\n") do',
    '  local by_text = gloss[text]',
    '  if not by_text then by_text = {} gloss[text] = by_text end',
    '  by_text[code] = def',
    'end',
    'return gloss',
    '',
  ].join('\n');
}

/** One output file. */
export interface RimeFileSink {
  write(chunk: string): void;
  close(): void;
}

/**
 * Everything the build touches outside the dictionary itself.
 *
 * Injected rather than mocked so the streaming and file-writing paths can be tested
 * without a real 9MB asset, which is the only part of this script that is not a thin
 * translation of `RimeDictWriter`.
 */
export interface RimeBuildDeps {
  exists(path: string): boolean;
  readAsset(path: string): Uint8Array;
  ensureDir(path: string): void;
  openFile(path: string): RimeFileSink;
  copyFile(from: string, to: string): void;
}

const nodeDeps: RimeBuildDeps = {
  exists: (p) => fs.existsSync(p),
  readAsset: (p) => new Uint8Array(fs.readFileSync(p)),
  ensureDir: (p) => fs.mkdirSync(p, { recursive: true }),
  copyFile: (from, to) => fs.copyFileSync(from, to),
  openFile: (p) => {
    const fd = fs.openSync(p, 'w');
    let buffered: string[] = [];
    return {
      write(chunk) {
        buffered.push(chunk);
        if (buffered.length >= FLUSH_INTERVAL) {
          fs.writeSync(fd, buffered.join('\n') + '\n');
          buffered = [];
        }
      },
      close() {
        if (buffered.length > 0) fs.writeSync(fd, buffered.join('\n') + '\n');
        fs.closeSync(fd);
      },
    };
  },
};

/** Per-script outcome, reported so a truncated build is visible rather than silent. */
export interface RimeScriptStats {
  rows: number;
  skipped: number;
  unencodable: number;
  duplicates: number;
}

export interface RimeBuildStats {
  entryCount: number;
  files: Record<RimeScript, string>;
  scripts: Record<RimeScript, RimeScriptStats>;
  /** Distinct candidate texts that carry a definition, i.e. the sidecar's size. */
  glossEntries: number;
  /** The Lua gloss sidecar, written next to the dictionaries. */
  glossFile: string;
}

export interface RimeBuildOptions {
  btreePath: string;
  outDir: string;
}

/**
 * Renders the hand-written files for one platform into `outDir`.
 *
 * Templates are read from disk directly rather than through `deps`: they are committed
 * source, small, and the same in a test as in a build.
 */
export function renderPlatformFiles(
  platform: RimePlatform,
  outDir: string,
  deps: RimeBuildDeps = nodeDeps,
  templatesDir: string = TEMPLATES_DIR
): string[] {
  const written: string[] = [];
  for (const name of TEMPLATE_FILES) {
    const template = fs.readFileSync(path.join(templatesDir, name), 'utf8');
    const target = path.join(outDir, name);
    deps.ensureDir(path.dirname(target));
    const sink = deps.openFile(target);
    sink.write(renderTemplate(name, template, platform).replace(/\n$/, ''));
    sink.close();
    written.push(target);
  }
  return written;
}

/**
 * Walks the asset once and writes every dictionary from it.
 *
 * A single pass feeds both scripts: the traditional rows are derived from the same
 * entry, and a second pass would re-read 9MB of pages for no new information.
 */
export async function buildRimeDictionaries(
  options: RimeBuildOptions,
  deps: RimeBuildDeps = nodeDeps
): Promise<RimeBuildStats> {
  if (!deps.exists(options.btreePath)) {
    throw new Error(
      `The dictionary asset is missing: ${options.btreePath}\n` +
        'Run "npm run build:dict" to generate it before "npm run build:rime".'
    );
  }

  const dictionary = await BTreeDictionary.open(
    new MemoryPageSource(deps.readAsset(options.btreePath))
  );

  deps.ensureDir(options.outDir);

  const entryCount = dictionary.entryCount;
  const files = {} as Record<RimeScript, string>;
  const writers = {} as Record<RimeScript, RimeDictWriter>;
  const sinks = {} as Record<RimeScript, RimeFileSink>;
  // Every definition the dictionaries carry, collected as the rows are written so the Lua
  // sidecar can be emitted in the same pass. Keyed by text then code because one text can
  // have several readings and each reading has its own definition.
  const gloss = new Map<string, Map<string, string>>();

  for (const script of RIME_SCRIPTS) {
    const name = DICT_NAMES[script];
    const filePath = path.join(options.outDir, `${name}.dict.yaml`);
    const sink = deps.openFile(filePath);
    sink.write(
      renderDictHeader({
        name,
        version: DICT_VERSION,
        entryCount,
      })
    );
    writers[script] = new RimeDictWriter(
      { name, version: DICT_VERSION, entryCount },
      script,
      (row) => {
        if (row.comment) {
          let byCode = gloss.get(row.text);
          if (!byCode) {
            byCode = new Map();
            gloss.set(row.text, byCode);
          }
          byCode.set(row.code, row.comment);
        }
        sink.write(formatRow(row));
      }
    );
    files[script] = filePath;
    sinks[script] = sink;
  }

  await dictionary.scanPrefix('', (entry) => {
    for (const script of RIME_SCRIPTS) writers[script].add(entry);
    return true;
  });

  for (const script of RIME_SCRIPTS) {
    writers[script].finish();
    sinks[script].close();
  }

  // The Lua gloss sidecar, so the schema's filter can put a definition on each candidate.
  // Written from the same pass as the dictionaries, keyed by the deduplicated rows.
  const glossFile = path.join(options.outDir, 'lua', 'pinyinduck_gloss.lua');
  deps.ensureDir(path.dirname(glossFile));
  const glossSink = deps.openFile(glossFile);
  glossSink.write(renderGlossSidecar(gloss));
  glossSink.close();

  const scripts = {} as Record<RimeScript, RimeScriptStats>;
  for (const script of RIME_SCRIPTS) {
    scripts[script] = {
      rows: writers[script].rowCount,
      skipped: writers[script].skippedCount,
      unencodable: writers[script].unencodableCount,
      duplicates: writers[script].duplicateCount,
    };
  }

  return { entryCount, files, scripts, glossEntries: gloss.size, glossFile };
}

export interface RimeCliOptions {
  btreePath: string;
  platforms: RimePlatform[];
  /** Overrides the output directory. Only accepted with a single platform. */
  outDir?: string;
}

/**
 * Resolves the CLI flags into build options.
 *
 * Split out from `main` so the flag handling can be tested without running a build.
 */
export function parseArgs(args: string[]): RimeCliOptions {
  const platforms = parsePlatformFlag(args);

  const outDir = flagValue(args, '--out');
  if (outDir !== undefined && platforms.length > 1) {
    throw new Error('--out writes one platform; pass --platform with it.');
  }

  return { btreePath: flagValue(args, '--btree') ?? DEFAULT_BTREE, platforms, outDir };
}

/** Builds and reports, so the CLI is a thin wrapper that tests can drive directly. */
export async function main(args: string[], deps: RimeBuildDeps = nodeDeps): Promise<void> {
  const { btreePath, platforms, outDir: outOverride } = parseArgs(args);
  const started = Date.now();
  console.log('Building the PinyinDuck Rime files from the B+ tree asset...');

  // The dictionaries and the gloss sidecar are the same bytes for every platform, so the
  // asset is walked once, for the first platform, and the output is copied to the rest.
  let built: { outDir: string; generated: string[] } | undefined;

  for (const platform of platforms) {
    const outDir = outOverride ?? platformRimeDir(platform);
    const { host, userDir, installCommand } = PLATFORM_INFO[platform];
    console.log(`\n[${platform}] ${host}`);

    for (const file of renderPlatformFiles(platform, outDir, deps)) {
      console.log(`  wrote   ${file}`);
    }

    if (built === undefined) {
      const stats = await buildRimeDictionaries({ btreePath, outDir }, deps);
      console.log(`  source  ${btreePath} (${stats.entryCount} entries)`);
      for (const script of RIME_SCRIPTS) {
        const { rows, skipped, unencodable, duplicates } = stats.scripts[script];
        console.log(
          `  wrote   ${stats.files[script]} ` +
            `(${rows} rows, ${duplicates} duplicates dropped, ` +
            `${unencodable} unreadable readings, ${skipped} missing text)`
        );
      }
      console.log(`  wrote   ${stats.glossFile} (${stats.glossEntries} definitions)`);
      built = { outDir, generated: [...RIME_SCRIPTS.map((s) => stats.files[s]), stats.glossFile] };
    } else {
      for (const from of built.generated) {
        const to = path.join(outDir, path.relative(built.outDir, from));
        deps.ensureDir(path.dirname(to));
        deps.copyFile(from, to);
        console.log(`  copied  ${to}`);
      }
    }
    console.log(`  next    in packages/${platform}, run \`${installCommand}\` to copy these into ${userDir}`);
  }

  console.log(`\nDone in ${((Date.now() - started) / 1000).toFixed(1)}s.`);
}

// pathToFileURL rather than a `file://` template, which never matches a Windows path
// (`C:\...`) or one with a space in it (%20 in the URL).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}
