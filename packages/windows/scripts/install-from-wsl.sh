#!/usr/bin/env bash
#
# install-from-wsl.sh — Installs the PinyinDuck Rime schemas into the Weasel user folder
# from WSL, so Windows needs neither Node nor a copy of the repository.
#
# Does what install.ps1 does, but from the Linux side: copies the two schemas, the Lua
# gloss filter and the generated dictionaries from packages/windows/rime into the
# Windows user's %APPDATA%\Rime (reached through /mnt/c), and merges the two schemes into
# their default.custom.yaml with WSL's own Node. Run `npm run build:rime` first: every
# file in packages/windows/rime is generated and none is committed.
#
# The user's own files are left alone, exactly as with install.ps1: default.custom.yaml
# is merged rather than replaced (an existing one is backed up and gets only the entries
# it is missing; one that already has them is not written), and rime.lua is never
# touched.
#
# The Windows Rime folder is found by asking Windows for %APPDATA% through
# powershell.exe. Set PINYINDUCK_RIME_DIR to install somewhere else instead, such as a
# scratch folder for a test.
#
# Usage:
#   bash packages/windows/scripts/install-from-wsl.sh
#
set -euo pipefail

SOURCE_DIR="$(cd "$(dirname "$0")/../rime" && pwd)"
REPO_ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
# Shared with install.ps1 and the macOS installer, which have the same file to merge.
MERGE_SCRIPT='packages/rime/scripts/install-default-custom.ts'

# Both dictionaries and both schemas have to be present together: a schema naming a
# dictionary that is missing fails to compile, and Weasel then silently falls back to
# its own default scheme, which looks like the install did nothing. The Lua gloss filter
# and its sidecar are required too: without them the schema still works but shows no
# definitions.
REQUIRED_FILES=(
  'pinyinduck.schema.yaml'
  'pinyinduck_trad.schema.yaml'
  'default.custom.yaml'
  'pinyinduck.dict.yaml'
  'pinyinduck_trad.dict.yaml'
  'lua/pinyinduck_gloss_filter.lua'
  'lua/pinyinduck_gloss.lua'
)

format_size() {
  awk -v b="$1" 'BEGIN { printf "%.1f MB", b / 1048576 }'
}

# The Windows user's Rime folder, as a WSL path. %APPDATA% is asked of Windows rather
# than guessed from /mnt/c/Users/$USER, because the Windows and WSL user names often
# differ and APPDATA can be redirected.
windows_rime_dir() {
  if ! command -v powershell.exe >/dev/null 2>&1 || ! command -v wslpath >/dev/null 2>&1; then
    echo 'powershell.exe or wslpath was not found, so this does not look like WSL with' >&2
    echo 'Windows interop on. Run it from WSL, or set PINYINDUCK_RIME_DIR to the Rime folder.' >&2
    exit 1
  fi
  local appdata
  # powershell.exe ends its output with \r\n.
  appdata="$(powershell.exe -NoProfile -NonInteractive -Command \
    '[Environment]::GetFolderPath("ApplicationData")' | tr -d '\r')"
  if [[ -z "$appdata" ]]; then
    echo 'Windows did not report an APPDATA folder. Set PINYINDUCK_RIME_DIR to the Rime folder.' >&2
    exit 1
  fi
  echo "$(wslpath -u "$appdata")/Rime"
}

echo ''
echo 'PinyinDuck -> Rime (Weasel, from WSL)'
echo ''

missing=()
for name in "${REQUIRED_FILES[@]}"; do
  if [[ ! -f "$SOURCE_DIR/$name" ]]; then
    missing+=("$name")
  fi
done

if [[ ${#missing[@]} -gt 0 ]]; then
  # Every file here is generated by the same build, so this is always the cause.
  echo "The generated files are missing from $SOURCE_DIR." >&2
  echo '' >&2
  echo 'Run this from the repository root first:' >&2
  echo '' >&2
  echo '    npm run build:dict' >&2
  echo '    npm run build:rime' >&2
  echo '' >&2
  echo "Missing file(s): ${missing[*]}" >&2
  exit 1
fi

if ! command -v npx >/dev/null 2>&1; then
  echo 'npx was not found. Node is needed to merge default.custom.yaml; it is the same' >&2
  echo 'Node that ran `npm run build:rime`, so put it on PATH and run this again.' >&2
  exit 1
fi

RIME_DIR="${PINYINDUCK_RIME_DIR:-$(windows_rime_dir)}"

echo "  source  $SOURCE_DIR"
echo "  target  $RIME_DIR"
echo ''

if [[ ! -d "$RIME_DIR" ]]; then
  mkdir -p "$RIME_DIR"
  echo '  created the Rime user folder (Weasel may not be installed yet)'
fi

# The Lua gloss sidecar lives in a subdirectory, which has to exist before it is copied.
mkdir -p "$RIME_DIR/lua"

for name in "${REQUIRED_FILES[@]}"; do
  # Merged below instead of copied, so the user's own entries survive.
  [[ "$name" == 'default.custom.yaml' ]] && continue
  source="$SOURCE_DIR/$name"
  cp -f "$source" "$RIME_DIR/$name"
  printf '  copied  %-32s %10s\n' "$name" "$(format_size "$(wc -c < "$source")")"
done

(cd "$REPO_ROOT" && npx --no-install tsx "$MERGE_SCRIPT" \
  "$SOURCE_DIR/default.custom.yaml" "$RIME_DIR/default.custom.yaml")

# Earlier versions of the installer replaced rime.lua with one defining the filter as a
# global. The schema no longer uses it, but it still loads the 15MB gloss table, so say so
# rather than edit a file that may hold the user's own components too.
if [[ -f "$RIME_DIR/rime.lua" ]] && grep -q 'pinyinduck_gloss_filter' "$RIME_DIR/rime.lua"; then
  echo "  note    $RIME_DIR/rime.lua still defines pinyinduck_gloss_filter from an"
  echo '          earlier install. Nothing uses it now: delete those lines, or the whole'
  echo '          file if PinyinDuck is the only thing in it.'
fi

# Rime keeps compiled output in a build subfolder. Its checksums would otherwise make
# Weasel reuse a stale table if a dictionary were regenerated with the same name.
if [[ -d "$RIME_DIR/build" ]]; then
  echo '  cleared the previous build so the dictionaries are recompiled'
  rm -rf "$RIME_DIR/build"
fi

echo ''
echo 'Installed.'
echo ''
echo 'Make Weasel rebuild the dictionaries:'
echo '  Right-click the Weasel tray icon -> 用户资料 -> 重新部署'
echo '  (User data -> Deploy)'
echo ''
echo 'Then add it to Windows:'
echo '  1. Settings -> Time & language -> Language & region'
echo '  2. Add a language -> 中文(中国) -> 拼音Duck is a Rime scheme, so it appears'
echo '     under the Rime input once Weasel has been installed and deployed'
echo '  3. Switch to it with Win+Space, and between the simplified and traditional'
echo '     schemes with F4 or Ctrl+`'
echo ''
echo 'The first deploy compiles 122k rows and takes a few seconds. The second'
echo 'scheme switch is instant.'
