<#
.SYNOPSIS
  Installs the PinyinDuck Rime schemas into the Weasel user folder.

.DESCRIPTION
  Copies the two schemas, the Lua gloss filter and the generated dictionaries into
  %APPDATA%\Rime, and adds the two schemes to the user's default.custom.yaml, then makes
  Weasel rebuild them. Everything is copied from this
  repository's packages\windows\rime folder, so run `npm run build:rime` first: every
  file in it is generated (the schemas from packages\rime\templates, the dictionaries
  from the shared CC-CEDICT asset) and none is committed.

  Weasel recompiles a dictionary whenever the .dict.yaml file changes, so reinstalling
  after a rebuild is just this script again.

  The user's own files are left alone. Every file copied has a PinyinDuck name, and
  default.custom.yaml, which holds the user's scheme list and hotkeys, is merged rather
  than replaced: an existing one is backed up and gets only the entries it is missing,
  and one that already has them is not written at all. rime.lua is never touched; the
  filter is the lua\pinyinduck_gloss_filter.lua module, which the schema loads by name.
  The merge runs on Node, which `npm run build:rime` needs anyway.

.PARAMETER Deploy
  Try to run Rime's command line deployer if the installed Weasel ships one. Older
  builds do, newer ones drive deployment from the tray menu, so this is best-effort and
  the script always prints the manual step as well.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File packages\windows\scripts\install.ps1
#>
[CmdletBinding()]
param(
  [switch]$Deploy
)

$ErrorActionPreference = 'Stop'

$SourceDir = Join-Path $PSScriptRoot '..\rime'
$RepoRoot = Join-Path $PSScriptRoot '..\..\..'
$MergeScript = Join-Path $PSScriptRoot '..\..\rime\scripts\install-default-custom.ts'
$RimeDir = Join-Path $env:APPDATA 'Rime'

# Both dictionaries and both schemas have to be present together: a schema naming a
# dictionary that is missing fails to compile, and Weasel then silently falls back to
# its own default scheme, which looks like the install did nothing. The Lua gloss filter
# and its sidecar are required too: without them the schema still works but shows no
# definitions.
$RequiredFiles = @(
  'pinyinduck.schema.yaml',
  'pinyinduck_trad.schema.yaml',
  'default.custom.yaml',
  'pinyinduck.dict.yaml',
  'pinyinduck_trad.dict.yaml',
  'lua\pinyinduck_gloss_filter.lua',
  'lua\pinyinduck_gloss.lua'
)

function Format-Size([long]$Bytes) {
  '{0:N1} MB' -f ($Bytes / 1MB)
}

Write-Host 'PinyinDuck -> Rime (Weasel)' -ForegroundColor Cyan
Write-Host ''

$missing = @()
foreach ($name in $RequiredFiles) {
  if (-not (Test-Path (Join-Path $SourceDir $name))) { $missing += $name }
}

if ($missing.Count -gt 0) {
  # Every file here is generated by the same build, so this is always the cause.
  Write-Host @"
The generated files are missing from $SourceDir.

Run this from the repository root first:

    npm run build:dict
    npm run build:rime
"@
  Write-Error "Missing file(s): $($missing -join ', ')"
}

if (-not (Get-Command npx -ErrorAction SilentlyContinue)) {
  Write-Error ('npx was not found. Node is needed to merge default.custom.yaml; it is the ' +
    'same Node that ran `npm run build:rime`, so put it on PATH and run this again.')
}

Write-Host "  source  $SourceDir"
Write-Host "  target  $RimeDir"
Write-Host ''

if (-not (Test-Path $RimeDir)) {
  New-Item -ItemType Directory -Path $RimeDir -Force | Out-Null
  Write-Host '  created the Rime user folder (Weasel may not be installed yet)'
}

# The Lua gloss sidecar lives in a subdirectory, which has to exist before it is copied.
$luaDir = Join-Path $RimeDir 'lua'
if (-not (Test-Path $luaDir)) {
  New-Item -ItemType Directory -Path $luaDir -Force | Out-Null
}

foreach ($name in $RequiredFiles) {
  # Merged below instead of copied, so the user's own entries survive.
  if ($name -eq 'default.custom.yaml') { continue }
  $source = Join-Path $SourceDir $name
  Copy-Item -Path $source -Destination (Join-Path $RimeDir $name) -Force
  $size = Format-Size (Get-Item $source).Length
  Write-Host ("  copied  {0,-32} {1,10}" -f $name, $size)
}

Push-Location $RepoRoot
try {
  & npx --no-install tsx $MergeScript (Join-Path $SourceDir 'default.custom.yaml') (Join-Path $RimeDir 'default.custom.yaml')
  if ($LASTEXITCODE -ne 0) { Write-Error 'Could not install default.custom.yaml.' }
} finally {
  Pop-Location
}

# Earlier versions of this installer replaced rime.lua with one defining the filter as a
# global. The schema no longer uses it, but it still loads the 15MB gloss table, so say so
# rather than edit a file that may hold the user's own components too.
$userRimeLua = Join-Path $RimeDir 'rime.lua'
if ((Test-Path $userRimeLua) -and (Select-String -Path $userRimeLua -Pattern 'pinyinduck_gloss_filter' -Quiet)) {
  Write-Host "  note    $userRimeLua still defines pinyinduck_gloss_filter from an"
  Write-Host '          earlier install. Nothing uses it now: delete those lines, or the whole'
  Write-Host '          file if PinyinDuck is the only thing in it.'
}

# Rime keeps compiled output in a build subfolder. Its checksums would otherwise make
# Weasel reuse a stale table if a dictionary were regenerated with the same name.
$buildDir = Join-Path $RimeDir 'build'
if (Test-Path $buildDir) {
  Write-Host '  cleared the previous build so the dictionaries are recompiled'
  Remove-Item -Path $buildDir -Recurse -Force
}

Write-Host ''

$deployed = $false
if ($Deploy) {
  $deployers = @(
    (Join-Path $env:ProgramFiles 'Rime\rime_deployer.exe'),
    (Join-Path ${env:ProgramFiles(x86)} 'Rime\rime_deployer.exe'),
    (Join-Path $env:LOCALAPPDATA 'Programs\Rime\rime_deployer.exe')
  ) | Where-Object { $_ -and (Test-Path $_) }

  foreach ($deployer in $deployers) {
    Write-Host "  deploying with $deployer"
    & $deployer --build pinyinduck --build pinyinduck_trad deploy | Out-Null
    if ($LASTEXITCODE -eq 0) {
      $deployed = $true
      break
    }
  }
}

Write-Host 'Installed.' -ForegroundColor Green
Write-Host ''
if (-not $deployed) {
  Write-Host 'Make Weasel rebuild the dictionaries:' -ForegroundColor Yellow
  Write-Host '  Right-click the Weasel tray icon -> 用户资料 -> 重新部署'
  Write-Host '  (User data -> Deploy)'
}
Write-Host ''
Write-Host 'Then add it to Windows:'
Write-Host '  1. Settings -> Time & language -> Language & region'
Write-Host '  2. Add a language -> 中文(中国) -> 拼音Duck is a Rime scheme, so it appears'
Write-Host '     under the Rime input once Weasel has been installed and deployed'
Write-Host '  3. Switch to it with Win+Space, and between the simplified and traditional'
Write-Host '     schemes with F4 or Ctrl+`'
Write-Host ''
Write-Host 'The first deploy compiles 122k rows and takes a few seconds. The second'
Write-Host 'scheme switch is instant.'
